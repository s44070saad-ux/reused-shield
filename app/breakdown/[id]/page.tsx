"use client";

import { useEffect, useState } from "react";
import Link from "next/link";
import { useParams, useRouter } from "next/navigation";
import { supabase, fmtNum } from "@/lib/supabaseClient";
import { PRODUCT_NAME, HONESTY_NOTE } from "@/lib/config";
import type { Breakdown } from "@/lib/breakdown";

interface Row { id: string; channel_title: string | null; created_at: string; plan: Breakdown }

function toMarkdown(p: Breakdown): string {
  const riskNotes = p.riskNotes ?? ((p as unknown as { dontCopy?: string[] }).dontCopy ?? []);
  const L: string[] = [];
  L.push(`# Channel Breakdown — ${p.channel.title}`);
  L.push(`Channel: ${p.channel.url} · ${fmtNum(p.channel.subs)} subscribers${p.channel.ageYears != null ? ` · ${p.channel.ageYears} years old` : ""}`);
  L.push(`Their reused-content risk estimate: ${p.risk.score}/100 (${p.risk.level})`);
  L.push(`\n## The numbers\n- Videos sampled: ${p.metrics.videosSampled}\n- Uploads/week: ~${p.metrics.uploadsPerWeek}\n- Average views: ${p.metrics.avgViews.toLocaleString()} · Median: ${p.metrics.medianViews.toLocaleString()}\n- Shorts: ${p.metrics.shortsPct}% of recent uploads`);
  L.push(`\n## Content pillars (true counts across the sample)`);
  p.pillars.forEach((x) => L.push(`- **${x.label}** — ${x.count} of ${p.metrics.videosSampled} sampled videos · e.g. ${x.examples[0] ?? ""}`));
  L.push(`\n## Top videos`);
  p.topVideos.forEach((v) => L.push(`- ${v.title} — ${v.views.toLocaleString()} views${v.ratio != null ? ` (${v.ratio}× subs)` : ""}`));
  L.push(`\n## What's working (observations from the data)`); p.strengths.forEach((s) => L.push(`- ${s}`));
  L.push(`\n## Gaps & weaknesses (observations from the data)`); p.weaknesses.forEach((s) => L.push(`- ${s}`));
  L.push(`\n## Their risk fingerprints`); riskNotes.forEach((s) => L.push(`- ${s}`));
  L.push(`\n---\nGenerated by ${PRODUCT_NAME}. Facts computed from public YouTube metadata. Risk figures are estimates from public signals; only YouTube decides monetization.`);
  return L.join("\n");
}

export default function BreakdownPage() {
  const { id } = useParams<{ id: string }>();
  const router = useRouter();
  const [row, setRow] = useState<Row | null>(null);
  const [others, setOthers] = useState<Row[]>([]);
  const [err, setErr] = useState("");
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    if (!supabase) { setLoading(false); return; }
    const sb = supabase;
    sb.auth.getSession().then(async ({ data }) => {
      if (!data.session) { router.replace("/login"); return; }
      const { data: r, error } = await sb.from("breakdowns").select("*").eq("id", id).single();
      if (error || !r) { setErr("Breakdown not found — or it belongs to a different account."); setLoading(false); return; }
      setRow(r as Row);
      const o = await sb.from("breakdowns").select("id, channel_title, created_at").neq("id", id).order("created_at", { ascending: false }).limit(8);
      if (o.data) setOthers(o.data as unknown as Row[]);
      setLoading(false);
    });
  }, [id, router]);

  function download() {
    if (!row) return;
    const blob = new Blob([toMarkdown(row.plan)], { type: "text/markdown" });
    const a = document.createElement("a");
    a.href = URL.createObjectURL(blob);
    a.download = `breakdown-${(row.plan.channel.title || "channel").replace(/[^\p{L}\p{N}]+/gu, "-").toLowerCase()}.md`;
    a.click();
    URL.revokeObjectURL(a.href);
  }

  if (loading) return <main className="wrap"><p className="muted" style={{ paddingTop: 40 }}>Loading breakdown…</p></main>;
  if (!row) return <main className="wrap"><div className="card"><p className="err">{err || "Breakdown not found."}</p><Link className="btn btn-sm" href="/finder">Back to Finder</Link></div></main>;

  const p = row.plan;
  const riskNotes = p.riskNotes ?? ((p as unknown as { dontCopy?: string[] }).dontCopy ?? []);
  const mins = p.metrics.avgLongDurationSec ? `${Math.floor(p.metrics.avgLongDurationSec / 60)}m ${p.metrics.avgLongDurationSec % 60}s` : "—";

  return (
    <main className="wrap">
      <div className="topbar no-print">
        <Link className="logo" href="/finder">← Finder</Link>
        <div style={{ display: "flex", gap: 8 }}>
          <button className="btn btn-ghost btn-sm" onClick={download}>Download breakdown (.md)</button>
          <Link className="btn btn-sm" href={`/dashboard?channel=${encodeURIComponent(p.channel.url)}`}>Audit this channel</Link>
        </div>
      </div>

      <section className="page-head">
        <h1>Breakdown: {p.channel.title}</h1>
        <p>
          <a href={p.channel.url} target="_blank" rel="noreferrer" style={{ color: "#7dd3fc" }}>{p.channel.url}</a>
          {" · "}{fmtNum(p.channel.subs)} subscribers{p.channel.ageYears != null ? ` · ${p.channel.ageYears} years old` : ""}
          {" · "}their risk estimate: <b style={{ color: "#fff" }}>{p.risk.score}/100 ({p.risk.level})</b>
        </p>
        <p style={{ opacity: .85 }}>Facts computed from this channel's public data — counts are exact over the sampled videos. Observations are labelled as such; this page makes no predictions and offers no plan.</p>
      </section>

      <div className="clock-row" style={{ marginTop: 16 }}>
        <div className="clock"><b>{p.metrics.uploadsPerWeek}/wk</b><span className="muted">uploads ({p.metrics.videosSampled} sampled)</span></div>
        <div className="clock"><b>{fmtNum(p.metrics.avgViews)}</b><span className="muted">avg views · median {fmtNum(p.metrics.medianViews)}</span></div>
        <div className="clock"><b>{p.metrics.shortsPct}%</b><span className="muted">Shorts · long avg {mins}</span></div>
        <div className="clock"><b>{fmtNum(p.metrics.topVideoViews)}</b><span className="muted">top video views</span></div>
      </div>

      <h2>Content pillars</h2>
      <div className="grid grid-2">
        {p.pillars.map((x) => (
          <div className="card feature" key={x.label} style={{ marginTop: 0 }}>
            <h3>"{x.label}" <span className="muted" style={{ fontWeight: 400 }}>· {x.count} of {p.metrics.videosSampled} sampled videos</span></h3>
            <ul style={{ margin: 0, paddingLeft: 18 }}>{x.examples.map((e, i) => <li key={i} className="muted">{e}</li>)}</ul>
          </div>
        ))}
        {p.pillars.length === 0 && <p className="muted">No repeated phrase appears in 2+ recent titles — the channel's topics are varied or the sample is small.</p>}
      </div>

      <h2>Top videos</h2>
      <div className="card" style={{ overflowX: "auto" }}>
        <table>
          <thead><tr><th>Title</th><th>Views</th><th>vs subs</th></tr></thead>
          <tbody>
            {p.topVideos.map((v, i) => (
              <tr key={i}><td><a href={v.url} target="_blank" rel="noreferrer">{v.title}</a></td><td>{fmtNum(v.views)}</td><td>{v.ratio != null ? `${v.ratio}×` : "—"}</td></tr>
            ))}
          </tbody>
        </table>
        {p.topOpenings.length > 0 && <p className="muted" style={{ marginBottom: 0 }}>Repeated title openings: {p.topOpenings.map((o) => `"${o.phrase}…" ×${o.count}`).join(" · ")}</p>}
      </div>

      <div className="grid grid-2">
        <div>
          <h2>What's working</h2>
          <div className="card" style={{ marginTop: 0 }}><ul style={{ margin: 0, paddingLeft: 20 }}>{p.strengths.map((s, i) => <li key={i} style={{ marginBottom: 8 }}>{s}</li>)}{p.strengths.length === 0 && <li className="muted">No standout strength crossed the reporting threshold in the sampled public data.</li>}</ul></div>
        </div>
        <div>
          <h2>Gaps &amp; weaknesses</h2>
          <div className="card" style={{ marginTop: 0 }}><ul style={{ margin: 0, paddingLeft: 20 }}>{p.weaknesses.map((s, i) => <li key={i} style={{ marginBottom: 8 }}>{s}</li>)}</ul></div>
        </div>
      </div>

      <h2>Their risk fingerprints</h2>
      <div className="card" style={{ marginTop: 0, borderColor: "#fecaca", background: "#fff7f7" }}>
        <ul style={{ margin: 0, paddingLeft: 20 }}>{riskNotes.map((s, i) => <li key={i} style={{ marginBottom: 8 }}>{s}</li>)}</ul>
      </div>

      <div className="honesty">{HONESTY_NOTE}</div>

      {others.length > 0 && (
        <p className="muted no-print" style={{ marginTop: 24 }}>
          Your other breakdowns: {others.map((o, i) => (<span key={o.id}>{i > 0 ? " · " : ""}<Link href={`/breakdown/${o.id}`}>{o.channel_title ?? "Channel"}</Link></span>))}
        </p>
      )}
    </main>
  );
}
